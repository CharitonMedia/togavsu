#!/usr/bin/env python3
"""Verify committed API/MCP/coverage/marketplace outputs regenerate byte for byte."""
import os
from pathlib import Path
import subprocess
import sys

root = Path(__file__).resolve().parents[2]
paths = [
    "api/openapi/v1/openapi.json",
    "api/openapi/marketplace/openapi.json",
    "api/openapi/v1/mcp-tools.json",
    "docs/api/coverage.md",
    "docs/api/stage1-inventory.json",
    "docs/api/runtime-fixtures.json",
    "docs/api/scenario-manifest.json",
]
before = {path: (root / path).read_bytes() for path in paths}
env = os.environ.copy()
env["PYTHONPATH"] = str(root / "api")
for module in ("contract.build", "contract.stage1_check"):
    subprocess.run([sys.executable, "-m", module], cwd=root, env=env, check=True)
changed = [path for path in paths if before[path] != (root / path).read_bytes()]
if changed:
    raise SystemExit("Generated bytes changed: " + ", ".join(changed))
subprocess.run(["git", "diff", "--exit-code", "--", *paths], cwd=root, check=True)
print(f"All {len(paths)} generated outputs match byte for byte.")
